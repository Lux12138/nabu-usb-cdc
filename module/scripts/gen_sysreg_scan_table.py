    # S3_6_C0_C0_0.  T49 section 2 classes op1 in {4,6} as "EL2/EL3, will
    # trap"; op1=6 with CRn=CRm=op2=0 has no architectural MRS assignment, so
    # it should raise EC=0x00 UNCATEGORIZED, which the CONFIG_XNUPOST
    # expected-fault branch claims.  Marked group 1: unreachable unless
    # nabu-sysregscan-trap=1, because an EC=0x18 (MSR/MRS trap) would panic.
