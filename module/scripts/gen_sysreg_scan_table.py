def encode(op0, op1, crn, crm, op2):
    return (0xd5000000
            | (1 << 21)          # bit21 = READ (MRS)
            | ((op0 & 3) << 19)
            | ((op1 & 7) << 16)
            | ((crn & 15) << 12)
            | ((crm & 15) << 8)
            | ((op2 & 7) << 5))


def main(out_path):
    lines = []
    lines.append("/* SPDX-License-Identifier: MIT")
    lines.append(" * AUTO-GENERATED by tools/gen_sysreg_scan_table.py -- do not edit.")
    lines.append(" * Regenerate, never hand-patch: the stubs must stay in one-to-one")
    lines.append(" * correspondence with the rows below.")
    lines.append(" */")
    lines.append("#ifndef NABU_SYSREG_SCAN_TABLE_H")
    lines.append("#define NABU_SYSREG_SCAN_TABLE_H")
    lines.append("")
    lines.append("struct nabu_scan_row {")
    lines.append("    const char *name;")
    lines.append("    uint32_t enc;          /* full MRS instruction word */")
    lines.append("    uint64_t (*fn)(void);  /* noinline stub, .inst <enc> */")
    lines.append("    uint8_t group;         /* 0 = read-safe at EL1, 1 = fault probe */")
    lines.append("};")
    lines.append("")
    for i, (name, o0, o1, cn, cm, o2, grp) in enumerate(ROWS):
        enc = encode(o0, o1, cn, cm, o2)
        lines.append("__attribute__((noinline)) static uint64_t "
                     "nabu_mrs_%d(void)" % i)
        lines.append("{")
        lines.append("#if defined(NABU_SCAN_HOST_TEST)")
        lines.append("    /* Host selftest never executes the encoding; it injects a")
        lines.append("     * reader through nabu_sysreg_scan(), so the stub only has to")
        lines.append("     * exist for the row table to reference. */")
        lines.append("    return nabu_scan_host_probe(0x%08xu);" % enc)
        lines.append("#else")
        lines.append("    uint64_t v;")
        lines.append("    __asm__ volatile(\".inst 0x%08x\\n\"" % enc)
        lines.append("                    \"mov %0, x0\"")
        lines.append("                    : \"=r\"(v)")
        lines.append("                    :")
        lines.append("                    : \"x0\", \"memory\");")
        lines.append("    return v;")
        lines.append("#endif")
        lines.append("}")
    lines.append("")
    lines.append("static const struct nabu_scan_row nabu_scan_rows[] = {")
    for i, (name, o0, o1, cn, cm, o2, grp) in enumerate(ROWS):
        enc = encode(o0, o1, cn, cm, o2)
        lines.append("    { \"%s\", 0x%08xu, nabu_mrs_%d, %d }," % (name, enc, i, grp))
    lines.append("};")
    lines.append("#define NABU_SCAN_ROWS ((unsigned)(sizeof(nabu_scan_rows) / sizeof(nabu_scan_rows[0])))")
    lines.append("#define NABU_SCAN_SAFE_ROWS %d" % sum(1 for r in ROWS if r[6] == 0))
    lines.append("")
    lines.append("#endif /* NABU_SYSREG_SCAN_TABLE_H */")
    with open(out_path, "w", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("rows=%d safe=%d trap=%d -> %s" %
          (len(ROWS), sum(1 for r in ROWS if r[6] == 0),
           sum(1 for r in ROWS if r[6] == 1), out_path))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "nabu_sysreg_scan_table.h")
